using JwtDemo.Core.Products;
using JwtDemo.Core.Users;
using Microsoft.EntityFrameworkCore.Storage;

namespace JwtDemo.Core;

public interface ITransactionProvider
{
    public ValueTask BeginTransactionAsync();
    public ValueTask CommitAsync();
    public ValueTask RollbackAsync();
}

public interface IUnitOfWork
{
    public IUserRepository UserRepository { get; }
    public IProductRepository ProductRepository { get; }
}

/// <summary>
///     Registered once per request scope and exposed as both <see cref="IUnitOfWork" /> and
///     <see cref="ITransactionProvider" /> (see Setup.RegisterServices).
///     A transaction which is neither committed nor rolled back - e.g. because an exception was thrown or
///     the request failed - is rolled back automatically when the request scope ends.
/// </summary>
public sealed class UnitOfWork(DatabaseContext context) : IUnitOfWork, ITransactionProvider, IAsyncDisposable
{
    private IDbContextTransaction? _transaction;

    // C# 14 'field' keyword: lazily created, backing field generated by the compiler
    public IUserRepository UserRepository => field ??= new UserRepository(context.Users);
    public IProductRepository ProductRepository => field ??= new ProductRepository(context.Products);

    public async ValueTask BeginTransactionAsync()
    {
        if (_transaction is not null)
        {
            throw new InvalidOperationException("Transaction already started");
        }

        _transaction = await context.Database.BeginTransactionAsync();
    }

    public async ValueTask CommitAsync()
    {
        if (_transaction is null)
        {
            throw new InvalidOperationException("No transaction started");
        }

        await context.SaveChangesAsync();
        await _transaction.CommitAsync();
        await DisposeTransactionAsync();
    }

    public async ValueTask RollbackAsync()
    {
        if (_transaction is null)
        {
            // nothing to roll back
            return;
        }

        await _transaction.RollbackAsync();
        await DisposeTransactionAsync();
    }

    public ValueTask DisposeAsync() => RollbackAsync();

    private async ValueTask DisposeTransactionAsync()
    {
        if (_transaction is not null)
        {
            await _transaction.DisposeAsync();
            _transaction = null;
        }
    }
}

public static class TransactionProviderExtensions
{
    extension(ITransactionProvider transaction)
    {
        /// <summary>
        ///     Commits the transaction, then returns the given result - handy in switch expressions:
        ///     <c>Success => await transaction.CommitAndReturn(NoContent())</c>
        /// </summary>
        public async ValueTask<TResult> CommitAndReturn<TResult>(TResult result)
        {
            await transaction.CommitAsync();

            return result;
        }
    }
}
